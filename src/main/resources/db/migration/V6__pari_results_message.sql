-- Публикация итогов пари: после расчета бот отправляет в канал сводку выплат
-- ответом на сообщение-опрос.

-- Отметка о том, что сводка уже ушла в канал. Заявка берется атомарным
-- UPDATE ... WHERE results_posted_at IS NULL, поэтому повторный расчет
-- (в том числе восстановительным планировщиком) не продублирует сообщение.
ALTER TABLE paris ADD COLUMN results_posted_at TIMESTAMP WITH TIME ZONE;

-- Уже рассчитанным пари сводка не полагается: она строится в момент расчета,
-- а не задним числом. Помечаем их как опубликованные, чтобы планировщик
-- не завалил каналы итогами по давно закрытым событиям.
UPDATE paris SET results_posted_at = settled_at WHERE settled_at IS NOT NULL;
