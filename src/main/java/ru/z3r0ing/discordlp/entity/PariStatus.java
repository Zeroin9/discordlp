package ru.z3r0ing.discordlp.entity;

/**
 * Жизненный цикл пари.
 */
public enum PariStatus {
    /** Идет прием ставок. */
    OPEN,
    /** Прием ставок остановлен, исход еще не объявлен. */
    RESOLVING,
    /** Исход объявлен, победителям начисляется выигрыш. */
    FINISHED,
    /** Пари аннулировано, ставки возвращаются участникам. */
    CANCELED
}
